"""
serve.app — the HTTP entry point of {{PACKAGE}}: the online adapter over the {{PORT_PREDICTOR}}
and {{PORT_MONITOR}} ports.

Generated by /vega-pack from the pytorch backend's serving templates; not a module of the
hexagon but an entry point, like predict.py. It builds nothing itself: the predictor, the
monitor and the raw-row reader come from predict.py, the bundle's one composition root, so the
HTTP path constructs the model, the recipe and the monitor exactly as the CLI path does — the
path the pack round trip verified.

    {{CMD}}-serve --bundle <bundle dir> --port {{PORT}} [--showcase DIR]
    python -m serve.app ...                  (inside the bundle)

This module is the composition only. The service is the closed list of route modules
ROUTE_MODULES (each `serve/routes_<name>.py`, those this bundle ships): each declares its
ENDPOINTS, the MODEL_ROUTES admitted at the model, the paths OPEN_WHILE_UNREADY and its
CAPABILITY as literals — pack reads them to write MANIFEST.serve.endpoints, which therefore
lists exactly the routes registered here — and a `register(app, state)`, and may declare an
`on_ready(state)` run once the self-test passed. `serve/startup.py` checks the files,
`serve/service.py` holds the state and the start-up, `serve/edge.py` decides before a route
runs (limits, admission, body bound, readiness gate, problem bodies).

Start-up. The bundle directory is resolved and every file of `serve/` is checked against the
digests MANIFEST.json pinned before any other module of it is imported: a service whose own
modules are not the packed ones answers every request 503, naming the file, and runs nothing
else. Then the code, the evidence and the data are verified and the contract is built
(`ServiceState.start`); a reason not to serve leaves the service unready, never raises out of
`create_app`. The lifespan loads the ports, runs the bundle's own self-test
(`predict.check_examples`) and each module's `on_ready`; /health turns 200 only then.

Errors. A request that breaks the input contract is refused whole with 422 and an RFC 9457
problem body naming every offending column; values the training part never showed are
answered, with per-row warnings. 503 while the service is not ready or the model is busy; 413
for a body over the bound; 500, with no internals, for a defect.
"""
# No postponed annotations (from __future__ import annotations) anywhere a route is declared:
# the route signatures refer to request models built at start-up, and FastAPI must resolve
# them as objects, not as strings.
import argparse
import json
import logging
import os
import sys
from pathlib import Path

from fastapi import FastAPI
from fastapi.responses import Response

HERE = Path(__file__).resolve().parent
CODE_HOME = HERE.parent          # where this service's code lives: the bundle, or site-packages
# first on the path, so a same-named package earlier on PYTHONPATH cannot win the import
if str(CODE_HOME) in sys.path:
    sys.path.remove(str(CODE_HOME))
sys.path.insert(0, str(CODE_HOME))

from serve import startup  # noqa: E402

__all__ = ["ROUTE_MODULES", "app_from_env", "create_app", "main"]

ROUTE_MODULES = ("routes_meta", "routes_predict", "routes_monitor", "routes_inspect",
                 "routes_showcase")
TITLE = {{TITLE_PY}}
DESCRIPTION = {{DESCRIPTION_PY}} + " See the model card shipped with the bundle."
NOT_READY = "Service not ready"


def create_app(bundle_dir=None, max_rows: int | None = None, torch_threads: int | None = None,
               max_inflight: int | None = None) -> FastAPI:
    """The service for one bundle. The bundle is read at start-up and never again."""
    root = startup.bundle_root(bundle_dir)
    manifest = startup.read_manifest(root)
    untrusted = startup.untrusted_serve(root, manifest)
    if untrusted:
        return _refused(startup.refusal(untrusted))
    from serve import edge, service
    limits = edge.Limits.resolve(root, os.environ, max_rows, torch_threads, max_inflight)
    state = service.ServiceState.start(root, limits)
    modules, problems = startup.route_modules(ROUTE_MODULES)
    state.refuse("; ".join(problems))
    app = FastAPI(title=TITLE, version=service.API_VERSION, description=DESCRIPTION,
                  lifespan=state.lifespan(modules), docs_url=None, redoc_url=None)
    app.state.service, app.state.contract = state, state.contract
    edge.install(app, state, edge.RouteTable.of(modules))
    for module in modules:
        module.register(app, state)
    return app


def _refused(why: str) -> FastAPI:
    """A service that answers every request 503 with `why`: what `serve/` holds is not what was
    packed, so nothing more of it is imported, let alone run."""
    body = json.dumps({"type": "about:blank", "title": NOT_READY, "status": 503,
                       "detail": why}).encode("utf-8")
    app = FastAPI(title=TITLE, docs_url=None, redoc_url=None, openapi_url=None)

    @app.middleware("http")
    async def refuse(request, call_next):
        return Response(body, status_code=503, media_type="application/problem+json")
    return app


def app_from_env() -> FastAPI:
    """Factory for `uvicorn --factory serve.app:app_from_env` (several workers)."""
    return create_app()


def _parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(description="Serve " + TITLE + " over HTTP.")
    ap.add_argument("--bundle", default=None,
                    help="the bundle directory (default: {{ENV}}_BUNDLE, this bundle, or the "
                         "working directory)")
    ap.add_argument("--host", default="127.0.0.1")
    ap.add_argument("--port", type=int, default={{PORT}})
    ap.add_argument("--workers", type=int, default=1)
    ap.add_argument("--torch-threads", type=int, default=None)
    ap.add_argument("--max-rows", type=int, default=None)
    ap.add_argument("--max-inflight", type=int, default=None,
                    help="requests at the model at once, per process (default: at most 2)")
    ap.add_argument("--showcase", default=None, metavar="DIR",
                    help="the showcase directory (default: {{ENV}}_SHOWCASE, else the bundle's "
                         "showcase/)")
    return ap


def _export(root: Path, a) -> None:
    """The options as the {{ENV}}_* variables every worker process reads."""
    os.environ["{{ENV}}_BUNDLE"] = str(root)
    for name, value in (("TORCH_THREADS", a.torch_threads), ("MAX_ROWS", a.max_rows),
                        ("MAX_INFLIGHT", a.max_inflight)):
        if value:
            os.environ[f"{{ENV}}_{name}"] = str(value)
    if a.showcase:
        os.environ["{{ENV}}_SHOWCASE"] = str(Path(a.showcase).resolve())


def main(argv=None) -> int:
    ap = _parser()
    a = ap.parse_args(argv)
    import uvicorn
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    try:
        root = startup.bundle_root(a.bundle)
    except FileNotFoundError as exc:
        ap.error(str(exc))
    _export(root, a)
    if a.workers > 1:
        uvicorn.run("serve.app:app_from_env", factory=True, host=a.host, port=a.port,
                    workers=a.workers)
    else:
        uvicorn.run(create_app(root), host=a.host, port=a.port)
    return 0


if __name__ == "__main__":
    sys.exit(main())
